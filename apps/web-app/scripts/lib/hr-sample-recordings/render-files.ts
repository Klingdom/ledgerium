/**
 * Renders the HR sample catalog to file contents (name -> text). Pure: the
 * generator writes these, and the test compares them with the committed files.
 */
import { buildSampleBundle, type SampleBundle } from './build-recording';
import { HR_SAMPLE_SCRIPTS } from './hr-catalog';

/** 2026-01-05T15:00:00Z; each recording starts one day after the previous one. */
const FIRST_START_MS = Date.UTC(2026, 0, 5, 15, 0, 0);
const DAY_MS = 24 * 60 * 60 * 1000;

export function buildHrSampleBundles(): Array<{ slug: string; bundle: SampleBundle }> {
  return HR_SAMPLE_SCRIPTS.map((script, i) => ({
    slug: script.slug,
    bundle: buildSampleBundle(script, FIRST_START_MS + i * DAY_MS),
  }));
}

function formatDuration(ms: number): string {
  const totalSeconds = Math.round(ms / 1000);
  const m = Math.floor(totalSeconds / 60);
  const s = totalSeconds % 60;
  return `${m}m ${String(s).padStart(2, '0')}s`;
}

function renderReadme(bundles: Array<{ slug: string; bundle: SampleBundle }>): string {
  const lines: string[] = [
    '# HR workflow sample recordings',
    '',
    '<!-- Generated by apps/web-app/scripts/generate-hr-sample-recordings.ts. Do not edit by hand. -->',
    '',
    `${bundles.length} example recordings of HR workflows across the employee lifecycle. Each file is a`,
    'session bundle in the same format the Ledgerium extension exports, so it can be uploaded',
    '(Upload a recording, or `POST /api/upload`) and produces a workflow, SOP and process map.',
    '',
    'How they are made: each workflow is a short script of browser actions. The script becomes raw',
    'recorder events, which run through the real sensitivity classifier, normalizer and segmenter.',
    'The steps are derived, not written by hand, and each one lists the events it came from.',
    '',
    'What they are not: these are synthetic sessions, not captures of real people. Screen and field',
    'names are representative of common HR tools (the app name comes from the domain, as in a real',
    'recording), not copies of any vendor product. As in a real recording, typed values are never',
    'captured, only that a field changed; on-screen labels are, so some steps click a link with a',
    "person's name. Every name in these files is fictional. Social Security Number and Taxpayer ID",
    'fields are flagged and redacted by the policy rules, as during a real recording.',
    '',
    'Regenerate with `pnpm --filter @ledgerium/web-app samples:hr`.',
    '',
  ];

  const byCategory = new Map<string, Array<{ slug: string; bundle: SampleBundle }>>();
  for (const entry of bundles) {
    const category = entry.bundle.manifest.sample.category;
    const list = byCategory.get(category) ?? [];
    list.push(entry);
    byCategory.set(category, list);
  }

  for (const [category, entries] of byCategory) {
    lines.push(`## ${category}`, '');
    lines.push('| Workflow | Apps | Events | Steps | Redacted fields | Duration | File |');
    lines.push('|---|---|---:|---:|---:|---:|---|');
    for (const { slug, bundle } of entries) {
      const apps = [
        ...new Set(
          bundle.normalizedEvents
            .map((e) => e.page_context?.applicationLabel)
            .filter((a): a is string => a !== undefined),
        ),
      ].join(', ');
      const redacted = new Set(
        bundle.normalizedEvents
          .filter((e) => e.normalization_meta.redactionApplied)
          .map((e) => e.target_summary?.selector ?? e.event_id),
      ).size;
      const duration = Date.parse(bundle.sessionJson.endedAt) - Date.parse(bundle.sessionJson.startedAt);
      lines.push(
        `| ${bundle.sessionJson.activityName} | ${apps} | ${bundle.normalizedEvents.length} | ` +
          `${bundle.derivedSteps.length} | ${redacted} | ${formatDuration(duration)} | [${slug}.json](./${slug}.json) |`,
      );
    }
    lines.push('');
    for (const { bundle } of entries) {
      lines.push(`- **${bundle.sessionJson.activityName}**: ${bundle.manifest.sample.summary}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

export function renderHrSampleFiles(): Record<string, string> {
  const bundles = buildHrSampleBundles();
  const files: Record<string, string> = {};
  for (const { slug, bundle } of bundles) {
    files[`${slug}.json`] = `${JSON.stringify(bundle, null, 2)}\n`;
  }
  files['README.md'] = renderReadme(bundles);
  return files;
}
