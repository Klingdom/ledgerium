/**
 * Catalog of sample HR workflow recordings, covering the employee lifecycle
 * from requisition to rehire.
 *
 * Each entry is a script of the browser actions one person takes to do the
 * task once. `build-recording.ts` turns a script into an uploadable bundle by
 * running it through the real normalizer and segmenter.
 *
 * Application names come from the domain, as in a real recording (the
 * normalizer labels an app by its domain). The vendors named are common
 * choices for each task, used as realistic settings; the screens and field
 * names are representative, not copies of any vendor's product.
 */
import type { SampleAction, SampleScript } from './build-recording';

// ── Action shorthands ────────────────────────────────────────────────────────
const open = (domain: string, route: string, page: string): SampleAction => ({ kind: 'open', domain, route, page });
const route = (r: string, page: string): SampleAction => ({ kind: 'route', route: r, page });
const click = (label: string): SampleAction => ({ kind: 'click', label });
const tab = (label: string): SampleAction => ({ kind: 'click', label, role: 'tab' });
const link = (label: string): SampleAction => ({ kind: 'click', label, role: 'link' });
const fill = (label: string, elementType?: string): SampleAction =>
  elementType === undefined ? { kind: 'fill', label } : { kind: 'fill', label, elementType };
const pick = (label: string): SampleAction => ({ kind: 'pick', label });
const submit = (label: string): SampleAction => ({ kind: 'submit', label });
const toast = (label: string): SampleAction => ({ kind: 'toast', label });
const modal = (label: string): SampleAction => ({ kind: 'modal', label });
const wait = (seconds: number): SampleAction => ({ kind: 'wait', ms: seconds * 1_000 });

